fn ensure_git_ltp_and_fio_built(
    cache_root: &Path,
    downloads: &Path,
    target_os: &str,
    target_arch: &str,
) -> Result<(PathBuf, Option<PathBuf>, PathBuf), String> {
    let target_git = cache_root
        .join("git")
        .join(format!("{target_os}-{target_arch}"))
        .join(GIT_VERSION);
    let legacy_git = cache_root.join("git").join(GIT_VERSION);

    let resolved_git = if valid_git_tree(&target_git, target_os, target_arch) {
        Some(target_git.clone())
    } else if valid_git_tree(&legacy_git, target_os, target_arch) {
        Some(legacy_git)
    } else {
        None
    };

    let target_ltp = cache_root
        .join("ltp")
        .join(format!("{target_os}-{target_arch}"))
        .join(format!("{LTP_VERSION}-jfs2"));
    let legacy_ltp = cache_root.join("ltp").join(LTP_VERSION);

    let resolved_ltp = if target_os != "linux" {
        None
    } else if valid_ltp_prefix(&target_ltp, target_os, target_arch) {
        Some(target_ltp.clone())
    } else if valid_ltp_prefix(&legacy_ltp, target_os, target_arch) {
        Some(legacy_ltp)
    } else {
        None
    };

    let target_fio = cache_root
        .join("fio")
        .join(format!("{target_os}-{target_arch}"))
        .join(FIO_VERSION)
        .join("fio");
    let resolved_fio = valid_fio_bin(&target_fio, target_os, target_arch).then(|| target_fio.clone());

    let need_git = resolved_git.is_none();
    let need_ltp = target_os == "linux" && resolved_ltp.is_none();
    let need_fio = resolved_fio.is_none();
    if !need_git && !need_ltp && !need_fio {
        return Ok((resolved_git.unwrap(), resolved_ltp, resolved_fio.unwrap()));
    }

    // Pre-download source tarballs on the host if needed so container/native build reuses cache.
    if need_ltp {
        let ltp_fname = format!("ltp-full-{LTP_VERSION}.tar.xz");
        let ltp_url = format!("https://github.com/linux-test-project/ltp/releases/download/{LTP_VERSION}/{ltp_fname}");
        download_cached(downloads, &ltp_fname, &ltp_url)?;
    }
    if need_fio {
        let fio_fname = format!("{FIO_VERSION}.tar.gz");
        let fio_url = format!("https://github.com/axboe/fio/archive/refs/tags/{FIO_VERSION}.tar.gz");
        download_cached(downloads, &fio_fname, &fio_url)?;
    }

    let (host_os, host_arch) = host_os_arch();
    let is_native = host_os == target_os && host_arch == target_arch;

    if is_native {
        let git_out = match resolved_git {
            Some(g) => g,
            None => {
                build_git_native(&target_git)?;
                target_git
            }
        };
        let fio_out = match resolved_fio {
            Some(f) => f,
            None => {
                build_fio_native(downloads, &target_fio, target_os, target_arch)?;
                target_fio
            }
        };
        let ltp_out = if target_os == "linux" {
            match resolved_ltp {
                Some(l) => Some(l),
                None => {
                    build_ltp_native(downloads, &target_ltp)?;
                    Some(target_ltp)
                }
            }
        } else {
            None
        };
        return Ok((git_out, ltp_out, fio_out));
    }

    if target_os == "linux" {
        build_linux_git_ltp_and_fio_via_docker(cache_root, target_arch, need_git, need_ltp, need_fio)?;
        let git_final = resolved_git.unwrap_or(target_git);
        if !valid_git_tree(&git_final, target_os, target_arch) {
            return Err(format!(
                "Docker build did not produce a valid {target_os}-{target_arch} git tree at {}",
                git_final.display()
            ));
        }
        if !valid_ltp_prefix(&target_ltp, target_os, target_arch) {
            return Err(format!(
                "Docker build did not produce a valid {target_os}-{target_arch} LTP prefix at {}",
                target_ltp.display()
            ));
        }
        let fio_final = resolved_fio.unwrap_or(target_fio);
        if !valid_fio_bin(&fio_final, target_os, target_arch) {
            return Err(format!(
                "Docker build did not produce a valid {target_os}-{target_arch} fio binary at {}",
                fio_final.display()
            ));
        }
        return Ok((git_final, Some(target_ltp), fio_final));
    }

    Err(format!(
        "cross-compiling embedded C suites from {host_os}-{host_arch} to {target_os}-{target_arch} is not supported; build natively on {target_os}-{target_arch}"
    ))
}

fn build_fio_native(downloads: &Path, dest_bin: &Path, target_os: &str, target_arch: &str) -> Result<(), String> {
    let archive = downloads.join(format!("{FIO_VERSION}.tar.gz"));
    let parent = dest_bin.parent().unwrap();
    fs::create_dir_all(parent).map_err(|e| e.to_string())?;
    let tmp_build = parent.join(format!(".fio-build-{}", std::process::id()));
    let _ = fs::remove_dir_all(&tmp_build);
    fs::create_dir_all(&tmp_build).map_err(|e| e.to_string())?;

    let st_tar = Command::new("tar")
        .arg("-xzf")
        .arg(&archive)
        .arg("-C")
        .arg(&tmp_build)
        .arg("--strip-components=1")
        .status()
        .map_err(|e| format!("tar -xzf {}: {e}", archive.display()))?;
    if !st_tar.success() {
        let _ = fs::remove_dir_all(&tmp_build);
        return Err(format!("extracting {} failed", archive.display()));
    }

    let mut ldflags = String::new();
    let mut cfg = Command::new("./configure");
    clean_native_make_env(&mut cfg);
    cfg.current_dir(&tmp_build).arg("--disable-native");
    if target_os == "linux" {
        cfg.arg("--disable-numa");
        // Build a tiny static `libaio.a` wrapper around the 5 Linux AIO syscalls so
        // `fio` supports `--ioengine=libaio` (and `io_uring`) with ZERO runtime dependency
        // on `libaio.so.1` or `libnuma.so.1` on minimal target hosts.
        let slib = tmp_build.join("fstest_static_libs");
        fs::create_dir_all(&slib).map_err(|e| e.to_string())?;
        let shim_c = slib.join("libaio_shim.c");
        let shim_o = slib.join("libaio_shim.o");
        let shim_a = slib.join("libaio.a");
        fs::write(&shim_c, LIBAIO_STATIC_SHIM_C).map_err(|e| e.to_string())?;
        let st_cc = Command::new("cc")
            .args(["-O2", "-c"])
            .arg(&shim_c)
            .arg("-o")
            .arg(&shim_o)
            .status()
            .map_err(|e| format!("cc libaio_shim.c: {e}"))?;
        if !st_cc.success() {
            let _ = fs::remove_dir_all(&tmp_build);
            return Err("compiling libaio_shim.c failed (ensure cc and libaio headers are installed)".into());
        }
        let st_ar = Command::new("ar")
            .args(["rcs"])
            .arg(&shim_a)
            .arg(&shim_o)
            .status()
            .map_err(|e| format!("ar libaio.a: {e}"))?;
        if !st_ar.success() {
            let _ = fs::remove_dir_all(&tmp_build);
            return Err("archiving static libaio.a failed".into());
        }
        ldflags = format!("-L{}", slib.display());
        cfg.env("LDFLAGS", &ldflags);
    }

    let st_cfg = cfg.status().map_err(|e| format!("fio configure: {e}"))?;
    if !st_cfg.success() {
        let _ = fs::remove_dir_all(&tmp_build);
        return Err("fio ./configure failed (ensure cc, make, and zlib headers are installed)".into());
    }

    let jobs = format!("-j{}", parallel_jobs());
    let mut mk = Command::new("make");
    clean_native_make_env(&mut mk);
    mk.current_dir(&tmp_build).args([jobs.as_str(), "fio"]);
    if !ldflags.is_empty() {
        mk.env("LDFLAGS", &ldflags);
    }
    let st_mk = mk.status().map_err(|e| format!("make fio: {e}"))?;
    if !st_mk.success() {
        let _ = fs::remove_dir_all(&tmp_build);
        return Err("building fio failed".into());
    }

    let built_bin = tmp_build.join("fio");
    if target_os == "macos" {
        let _ = Command::new("strip").args(["-x"]).arg(&built_bin).status();
        let _ = Command::new("codesign")
            .args(["-s", "-", "-f"])
            .arg(&built_bin)
            .status();
    } else if target_os == "linux" {
        maybe_strip_linux_elf(&built_bin, target_arch);
    }
    copy_file_preserve_mode(&built_bin, dest_bin)?;
    let _ = fs::remove_dir_all(&tmp_build);
    verify_binary_arch(dest_bin, target_os, target_arch)?;
    Ok(())
}

fn clean_native_make_env(cmd: &mut Command) -> &mut Command {
    // Strip Cargo build-script variables that upstream C Makefiles interpret
    // specially (notably Git's Makefile treats `PROFILE=release` as PGO
    // `-fprofile-use`, failing on Apple Clang for missing `default.profdata`).
    for key in [
        "PROFILE",
        "DEBUG",
        "OPT_LEVEL",
        "TARGET",
        "HOST",
        "CARGO_MAKEFLAGS",
        "MAKEFLAGS",
        "MFLAGS",
    ] {
        cmd.env_remove(key);
    }
    cmd
}

fn parallel_jobs() -> usize {
    std::thread::available_parallelism().map(|n| n.get()).unwrap_or(4)
}

fn build_git_native(dest: &Path) -> Result<(), String> {
    if let Some(p) = dest.parent() {
        fs::create_dir_all(p).map_err(|e| e.to_string())?;
    }
    if !dest.join("t/test-lib.sh").is_file() {
        let tmp = dest.with_extension(format!("clone-tmp-{}", std::process::id()));
        let _ = fs::remove_dir_all(&tmp);
        let st = Command::new("git")
            .args(["clone", "--depth", "1", "--branch", GIT_VERSION, GIT_REPO])
            .arg(&tmp)
            .status()
            .map_err(|e| format!("git clone failed: {e}"))?;
        if !st.success() {
            let _ = fs::remove_dir_all(&tmp);
            return Err(format!("git clone {GIT_REPO}@{GIT_VERSION} failed"));
        }
        let _ = fs::remove_dir_all(dest);
        fs::rename(&tmp, dest).map_err(|e| e.to_string())?;
    }
    let jobs = format!("-j{}", parallel_jobs());
    let has_perl = find_in_path("perl").is_some();
    let mut cmd = Command::new("make");
    clean_native_make_env(&mut cmd);
    cmd.current_dir(dest).args([
        jobs.as_str(),
        "NO_CURL=YesPlease",
        "NO_EXPAT=YesPlease",
        "NO_GETTEXT=YesPlease",
        "NO_TCLTK=YesPlease",
    ]);
    if !has_perl {
        cmd.arg("NO_PERL=YesPlease");
    }
    cmd.arg("all");
    let st = cmd.status().map_err(|e| format!("make git: {e}"))?;
    if !st.success() {
        return Err("building git failed (ensure cc, make, and zlib headers are installed)".into());
    }
    if !dest.join("t/helper/test-tool").is_file() {
        let mut cmd2 = Command::new("make");
        clean_native_make_env(&mut cmd2);
        let st2 = cmd2
            .current_dir(dest.join("t/helper"))
            .arg(&jobs)
            .status()
            .map_err(|e| format!("make t/helper: {e}"))?;
        if !st2.success() {
            return Err("building git t/helper/test-tool failed".into());
        }
    }
    Ok(())
}

fn build_ltp_native(downloads: &Path, prefix: &Path) -> Result<(), String> {
    let archive = downloads.join(format!("ltp-full-{LTP_VERSION}.tar.xz"));
    let build_parent = prefix.parent().unwrap();
    fs::create_dir_all(build_parent).map_err(|e| e.to_string())?;
    let src = build_parent.join(format!("ltp-src-{LTP_VERSION}"));
    if !src.join("configure").is_file() {
        let _ = fs::remove_dir_all(&src);
        let tmp_extract = build_parent.join(format!(".ltp-extract-{}", std::process::id()));
        let _ = fs::remove_dir_all(&tmp_extract);
        fs::create_dir_all(&tmp_extract).map_err(|e| e.to_string())?;
        let st = Command::new("tar")
            .arg("-xJf")
            .arg(&archive)
            .arg("-C")
            .arg(&tmp_extract)
            .status()
            .map_err(|e| format!("tar -xJf {}: {e}", archive.display()))?;
        if !st.success() {
            return Err(format!(
                "extracting {} failed (ensure tar + xz are installed)",
                archive.display()
            ));
        }
        fs::rename(tmp_extract.join(format!("ltp-full-{LTP_VERSION}")), &src).map_err(|e| e.to_string())?;
        let _ = fs::remove_dir_all(&tmp_extract);
    }
    let jobs = format!("-j{}", parallel_jobs());
    let mut cfg = Command::new("./configure");
    clean_native_make_env(&mut cfg);
    let st_cfg = cfg
        .current_dir(&src)
        .arg(format!("--prefix={}", prefix.display()))
        .status()
        .map_err(|e| format!("ltp configure: {e}"))?;
    if !st_cfg.success() {
        return Err("LTP ./configure failed (install gcc, make, pkgconf, bison, flex, m4, libc-dev)".into());
    }
    // Build internal LTP static libraries first (`libltp.a`, `libltpnewipc.a`, `libltpujson.a`, ...),
    // then build + install ONLY the filesystem-relevant test subtrees (`testcases/lib`,
    // `kernel/syscalls`, `kernel/fs`, `commands/df`, and `runtest`). This cuts Linux LTP compile
    // time by ~60% while installing 100% of `*_child`, `create_datafile`, `frag`, `fs_racer_*`,
    // and `testcases/data` helpers.
    for lib_dir in ["include", "lib", "libs"] {
        if src.join(lib_dir).join("Makefile").is_file() {
            let mut mk = Command::new("make");
            clean_native_make_env(&mut mk);
            let _ = mk.current_dir(src.join(lib_dir)).args([jobs.as_str(), "all"]).status();
        }
    }
    for sub in [
        "testcases/lib",
        "testcases/kernel/include",
        "testcases/kernel/lib",
        "testcases/kernel/syscalls",
        "testcases/kernel/fs",
        "testcases/kernel/io/writetest",
        "testcases/network/nfsv4/locks",
        "testcases/commands/df",
        "testcases/commands/shell",
    ] {
        let dir = src.join(sub);
        if dir.join("Makefile").is_file() {
            let mut mk1 = Command::new("make");
            clean_native_make_env(&mut mk1);
            let _ = mk1.current_dir(&dir).args([jobs.as_str(), "-k", "all"]).status();
            let mut mk2 = Command::new("make");
            clean_native_make_env(&mut mk2);
            let _ = mk2.current_dir(&dir).args(["-k", "install"]).status();
        }
    }
    let mut mk_run = Command::new("make");
    clean_native_make_env(&mut mk_run);
    let _ = mk_run.current_dir(src.join("runtest")).args(["-k", "install"]).status();
    let _ = fs::remove_dir_all(&src);
    if !prefix.join("runtest/syscalls").is_file()
        || !prefix.join("runtest/fs").is_file()
        || !prefix.join("testcases/bin").is_dir()
    {
        return Err(format!("LTP install incomplete under {}", prefix.display()));
    }
    Ok(())
}

/// Cross-build Linux `git`, `ltp`, and `fio` inside `debian:bullseye` (`glibc 2.31` universal
/// baseline compatible with Ubuntu 20.04+, Debian 11+, Amazon Linux 2023, Rocky 9+) using local Docker.
fn build_linux_git_ltp_and_fio_via_docker(
    cache_root: &Path,
    target_arch: &str,
    need_git: bool,
    need_ltp: bool,
    need_fio: bool,
) -> Result<(), String> {
    if find_in_path("docker").is_none() {
        return Err(format!(
            "docker is required to cross-compile Linux {target_arch} Git/LTP/Fio C suites from non-Linux host"
        ));
    }
    let platform = match target_arch {
        "x86_64" => "linux/amd64",
        "aarch64" => "linux/arm64",
        other => return Err(format!("unsupported Docker Linux arch {other}")),
    };
    let libaio_shim = LIBAIO_STATIC_SHIM_C;
    let script = format!(
        r#"set -eu
export DEBIAN_FRONTEND=noninteractive
apt-get update -qq
apt-get install -y -qq --no-install-recommends \
    ca-certificates git build-essential pkgconf bison flex m4 xz-utils \
    zlib1g-dev libaio-dev libacl1-dev libcap-dev libkeyutils-dev libnuma-dev uuid-dev libssl-dev attr perl
JOBS=$(nproc 2>/dev/null || echo 4)

if [ "{need_git}" = "true" ]; then
    GDIR="/cache/git/linux-{target_arch}/{GIT_VERSION}"
    mkdir -p "$(dirname "$GDIR")"
    if [ ! -f "$GDIR/t/test-lib.sh" ]; then
        rm -rf "$GDIR.tmp"
        git clone --depth 1 --branch "{GIT_VERSION}" "{GIT_REPO}" "$GDIR.tmp"
        rm -rf "$GDIR"
        mv "$GDIR.tmp" "$GDIR"
    fi
    make -C "$GDIR" -j"$JOBS" NO_CURL=YesPlease NO_EXPAT=YesPlease NO_GETTEXT=YesPlease NO_TCLTK=YesPlease all
    if [ ! -x "$GDIR/t/helper/test-tool" ]; then
        make -C "$GDIR/t/helper" -j"$JOBS"
    fi
    strip --strip-unneeded "$GDIR/git" "$GDIR/t/helper/test-tool" 2>/dev/null || true
fi

if [ "{need_fio}" = "true" ]; then
    FDEST="/cache/fio/linux-{target_arch}/{FIO_VERSION}/fio"
    FSRC="/tmp/fio-build"
    rm -rf "$FSRC"
    mkdir -p "$FSRC/fstest_static_libs" "$(dirname "$FDEST")"
    tar -xzf "/cache/downloads/{FIO_VERSION}.tar.gz" -C "$FSRC" --strip-components=1
    cat > "$FSRC/fstest_static_libs/libaio_shim.c" << 'EOF_LIBAIO'
{libaio_shim}
EOF_LIBAIO
    cc -O2 -c "$FSRC/fstest_static_libs/libaio_shim.c" -o "$FSRC/fstest_static_libs/libaio_shim.o"
    ar rcs "$FSRC/fstest_static_libs/libaio.a" "$FSRC/fstest_static_libs/libaio_shim.o"
    (cd "$FSRC" && LDFLAGS="-L$FSRC/fstest_static_libs" ./configure --disable-native --disable-numa && LDFLAGS="-L$FSRC/fstest_static_libs" make -j"$JOBS" fio)
    strip --strip-unneeded "$FSRC/fio" 2>/dev/null || true
    cp "$FSRC/fio" "$FDEST"
    chmod 0755 "$FDEST"
    rm -rf "$FSRC"
fi

if [ "{need_ltp}" = "true" ]; then
    LPREFIX="/cache/ltp/linux-{target_arch}/{LTP_VERSION}-jfs2"
    LSRC="/tmp/ltp-build"
    rm -rf "$LSRC" "$LPREFIX"
    mkdir -p "$LSRC" "$(dirname "$LPREFIX")"
    tar -xJf "/cache/downloads/ltp-full-{LTP_VERSION}.tar.xz" -C "$LSRC" --strip-components=1
    (cd "$LSRC" && ./configure --prefix="$LPREFIX")
    for libd in include lib libs; do
        [ -f "$LSRC/$libd/Makefile" ] && make -C "$LSRC/$libd" -j"$JOBS" all || true
    done
    for subd in testcases/lib testcases/kernel/include testcases/kernel/lib testcases/kernel/syscalls testcases/kernel/fs testcases/kernel/io/writetest testcases/network/nfsv4/locks testcases/commands/df testcases/commands/shell; do
        if [ -f "$LSRC/$subd/Makefile" ]; then
            make -C "$LSRC/$subd" -j"$JOBS" -k all || true
            make -C "$LSRC/$subd" -k install || true
        fi
    done
    make -C "$LSRC/runtest" -k install || true
    find "$LPREFIX/testcases/bin" -maxdepth 1 -type f -exec strip --strip-unneeded {{}} + 2>/dev/null || true
    rm -rf "$LSRC"
fi
"#
    );

    let mount_arg = format!("{}:/cache", cache_root.display());
    let st = Command::new("docker")
        .args([
            "run",
            "--rm",
            "--platform",
            platform,
            "-v",
            &mount_arg,
            "debian:bullseye",
            "sh",
            "-c",
            &script,
        ])
        .status()
        .map_err(|e| format!("docker run debian:bullseye failed: {e}"))?;
    if !st.success() {
        return Err(format!("Docker Linux {target_arch} Git/LTP build exited with {st}"));
    }
    Ok(())
}

fn stage_git_from_tree(tree: &Path, stage: &Path, target_os: &str, target_arch: &str) -> Result<Value, String> {
    let tree = tree.canonicalize().unwrap_or_else(|_| tree.to_path_buf());
    let dst = stage.join("git");
    fs::create_dir_all(dst.join("t/helper")).map_err(|e| e.to_string())?;

    let main_git = tree.join("git");
    let git_ino = fs::metadata(&main_git).map(|m| m.ino()).unwrap_or(0);
    copy_file_preserve_mode(&main_git, &dst.join("git"))?;
    if target_os == "linux" {
        maybe_strip_linux_elf(&dst.join("git"), target_arch);
    }
    verify_binary_arch(&dst.join("git"), target_os, target_arch)?;

    for ent in fs::read_dir(&tree).map_err(|e| e.to_string())?.flatten() {
        let p = ent.path();
        let name = ent.file_name().to_string_lossy().into_owned();
        if name == "git" {
            continue;
        }
        let Ok(meta) = fs::symlink_metadata(&p) else {
            continue;
        };
        if meta.is_symlink() && name.starts_with("git-") {
            let target = fs::read_link(&p).map_err(|e| e.to_string())?;
            let _ = std::os::unix::fs::symlink(target, dst.join(&name));
        } else if meta.is_file() {
            if (name.starts_with("git-") || name == "scalar") && (meta.permissions().mode() & 0o111 != 0) {
                // Convert Git's 145 hardlinked `git-*` builtins into relative symlinks to `git`
                // so extraction uses 0 extra MB instead of duplicating `git` 145 times!
                if name.starts_with("git-") && git_ino != 0 && meta.ino() == git_ino {
                    let _ = std::os::unix::fs::symlink("git", dst.join(&name));
                } else {
                    copy_file_preserve_mode(&p, &dst.join(&name))?;
                    if target_os == "linux" {
                        maybe_strip_linux_elf(&dst.join(&name), target_arch);
                    }
                }
            } else if matches!(
                name.as_str(),
                "GIT-BUILD-OPTIONS" | "GIT-VERSION-FILE" | "git-sh-setup" | "git-sh-i18n" | "git-mergetool--lib"
            ) || (name.starts_with("git-") && !name.contains('.'))
            {
                copy_file_preserve_mode(&p, &dst.join(&name))?;
            }
        }
    }
    for sub in ["bin-wrappers", "templates/blt", "perl/build/lib", "mergetools"] {
        if tree.join(sub).is_dir() {
            copy_dir_recursive(&tree.join(sub), &dst.join(sub))?;
        }
    }
    // Stage `test-tool`, `test-fake-ssh`, and any other compiled helper binaries in `t/helper/`.
    for ent in fs::read_dir(tree.join("t/helper"))
        .map_err(|e| e.to_string())?
        .flatten()
    {
        let p = ent.path();
        let name = ent.file_name().to_string_lossy().into_owned();
        if name.ends_with(".o") || name.ends_with(".c") || name.ends_with(".h") || name.ends_with(".sh") {
            continue;
        }
        let Ok(meta) = fs::symlink_metadata(&p) else {
            continue;
        };
        if meta.is_file() && (meta.permissions().mode() & 0o111 != 0) {
            let helper_dst = dst.join("t/helper").join(&name);
            copy_file_preserve_mode(&p, &helper_dst)?;
            if target_os == "linux" {
                maybe_strip_linux_elf(&helper_dst, target_arch);
            }
        }
    }
    verify_binary_arch(&dst.join("t/helper/test-tool"), target_os, target_arch)?;

    let mut script_count = 0usize;
    for ent in fs::read_dir(tree.join("t")).map_err(|e| e.to_string())?.flatten() {
        let p = ent.path();
        let name = ent.file_name().to_string_lossy().into_owned();
        if name == "helper"
            || name == "unit-tests"
            || name.starts_with("trash directory.")
            || name == "test-results"
            || name.ends_with(".o")
        {
            continue;
        }
        let Ok(meta) = fs::symlink_metadata(&p) else {
            continue;
        };
        if meta.is_dir() {
            copy_dir_recursive(&p, &dst.join("t").join(&name))?;
        } else {
            copy_file_preserve_mode(&p, &dst.join("t").join(&name))?;
            if name.starts_with('t') && name.ends_with(".sh") {
                script_count += 1;
            }
        }
    }

    Ok(json!({
        "gitVersion": GIT_VERSION,
        "originalBuildDir": tree.display().to_string(),
        "scripts": script_count,
    }))
}

fn stage_fio_from_bin(fio_bin: &Path, stage: &Path, target_os: &str, target_arch: &str) -> Result<Value, String> {
    let dst = stage.join("fio");
    fs::create_dir_all(&dst).map_err(|e| e.to_string())?;
    let out = dst.join("fio");
    copy_file_preserve_mode(fio_bin, &out)?;
    if target_os == "linux" {
        maybe_strip_linux_elf(&out, target_arch);
    }
    verify_binary_arch(&out, target_os, target_arch)?;
    Ok(json!({
        "fioVersion": FIO_VERSION,
        "bundledBinary": true,
    }))
}

fn stage_ltp_from_prefix(prefix: &Path, stage: &Path, target_os: &str, target_arch: &str) -> Result<Value, String> {
    let dst = stage.join("ltp");
    fs::create_dir_all(dst.join("runtest")).map_err(|e| e.to_string())?;
    fs::create_dir_all(dst.join("testcases/bin")).map_err(|e| e.to_string())?;

    let suites = [
        "syscalls",
        "fs",
        "fs_perms_simple",
        "fcntl-locktests",
        "fs_bind",
        "smoketest",
        "dio",
        "fs_readonly",
    ];
    let mut staged_suites = Vec::new();
    for s in suites {
        let rf = prefix.join("runtest").join(s);
        if rf.is_file() {
            fs::copy(&rf, dst.join("runtest").join(s)).map_err(|e| e.to_string())?;
            staged_suites.push(s);
        }
    }

    if prefix.join("testcases/data").is_dir() {
        copy_dir_recursive(&prefix.join("testcases/data"), &dst.join("testcases/data"))?;
    }

    // Copy every binary, child helper (`*_child`, `create_datafile`, `frag`, `tst_*`),
    // and `.sh` script installed under `testcases/bin` by our targeted syscalls+fs+lib build
    // so resource-copying and child-spawning LTP tests never hit missing-helper TBROKs.
    let mut bin_count = 0usize;
    let mut verified_one = false;
    for ent in fs::read_dir(prefix.join("testcases/bin"))
        .map_err(|e| e.to_string())?
        .flatten()
    {
        let p = ent.path();
        let name = ent.file_name().to_string_lossy().into_owned();
        let out_p = dst.join("testcases/bin").join(&name);
        let Ok(meta) = fs::symlink_metadata(&p) else {
            continue;
        };
        if meta.is_dir() {
            copy_dir_recursive(&p, &out_p)?;
        } else {
            copy_file_preserve_mode(&p, &out_p)?;
            if target_os == "linux" && !meta.file_type().is_symlink() {
                maybe_strip_linux_elf(&out_p, target_arch);
                if !verified_one && matches_target_binary(&out_p, target_os, target_arch) {
                    verified_one = true;
                }
            }
            bin_count += 1;
        }
    }
    if !verified_one {
        return Err(format!(
            "no valid {target_os}-{target_arch} ELF binaries staged from LTP {}",
            prefix.display()
        ));
    }

    Ok(json!({
        "ltpVersion": LTP_VERSION,
        "suites": staged_suites,
        "binaries": bin_count,
    }))
}

// ---------- Helpers ----------

fn find_in_path(name: &str) -> Option<PathBuf> {
    let path = env::var("PATH").ok()?;
    for dir in path.split(':') {
        let p = Path::new(dir).join(name);
        if p.is_file() {
            return Some(p);
        }
    }
    None
}

fn download_cached(downloads: &Path, filename: &str, url: &str) -> Result<PathBuf, String> {
    let dest = downloads.join(filename);
    if dest.is_file() && fs::metadata(&dest).map(|m| m.len() > 0).unwrap_or(false) {
        return Ok(dest);
    }
    fs::create_dir_all(downloads).map_err(|e| e.to_string())?;
    let tmp = downloads.join(format!(".{filename}.part-{}", std::process::id()));
    let _ = fs::remove_file(&tmp);

    let ok = if find_in_path("curl").is_some() {
        Command::new("curl")
            .args(["-fL", "--retry", "3", "-sS", "-o"])
            .arg(&tmp)
            .arg(url)
            .status()
            .map(|s| s.success())
            .unwrap_or(false)
    } else if find_in_path("wget").is_some() {
        Command::new("wget")
            .args(["-q", "-O"])
            .arg(&tmp)
            .arg(url)
            .status()
            .map(|s| s.success())
            .unwrap_or(false)
    } else {
        return Err("neither curl nor wget found on PATH to download suite archives".into());
    };
    if !ok {
        let _ = fs::remove_file(&tmp);
        return Err(format!("failed to download {url}"));
    }
    fs::rename(&tmp, &dest).map_err(|e| e.to_string())?;
    Ok(dest)
}

fn unpack_tar_gz(archive: &Path, dest: &Path) -> Result<(), String> {
    let f = File::open(archive).map_err(|e| format!("open {}: {e}", archive.display()))?;
    let mut ar = tar::Archive::new(GzDecoder::new(f));
    ar.set_preserve_permissions(true);
    ar.unpack(dest)
        .map_err(|e| format!("unpack {}: {e}", archive.display()))
}

fn matches_target_binary(path: &Path, target_os: &str, target_arch: &str) -> bool {
    let Ok(mut f) = File::open(path) else {
        return false;
    };
    let mut hdr = [0u8; 20];
    if f.read_exact(&mut hdr).is_err() {
        return false;
    }
    match (target_os, target_arch) {
        ("macos", "aarch64") => hdr[0..4] == [0xcf, 0xfa, 0xed, 0xfe] && hdr[4..8] == [0x0c, 0x00, 0x00, 0x01],
        ("macos", "x86_64") => hdr[0..4] == [0xcf, 0xfa, 0xed, 0xfe] && hdr[4..8] == [0x07, 0x00, 0x00, 0x01],
        ("linux", "x86_64") => hdr[0..4] == [0x7f, b'E', b'L', b'F'] && hdr[18..20] == [0x3e, 0x00],
        ("linux", "aarch64") => hdr[0..4] == [0x7f, b'E', b'L', b'F'] && hdr[18..20] == [0xb7, 0x00],
        _ => false,
    }
}

fn verify_binary_arch(path: &Path, target_os: &str, target_arch: &str) -> Result<(), String> {
    if matches_target_binary(path, target_os, target_arch) {
        Ok(())
    } else {
        Err(format!(
            "binary {} does not match expected target {target_os}-{target_arch}",
            path.display()
        ))
    }
}

fn maybe_strip_linux_elf(path: &Path, target_arch: &str) {
    let (host_os, host_arch) = host_os_arch();
    if host_os == "linux" && host_arch == target_arch && find_in_path("strip").is_some() {
        let _ = Command::new("strip").args(["--strip-unneeded"]).arg(path).status();
    }
}

fn sha256_prefix16(path: &Path) -> Result<String, String> {
    let mut f = File::open(path).map_err(|e| e.to_string())?;
    let mut hasher = Sha256::new();
    let mut buf = [0u8; 65536];
    loop {
        let n = f.read(&mut buf).map_err(|e| e.to_string())?;
        if n == 0 {
            break;
        }
        hasher.update(&buf[..n]);
    }
    let digest = hasher.finalize();
    let mut s = String::with_capacity(16);
    for b in &digest[..8] {
        s.push_str(&format!("{b:02x}"));
    }
    Ok(s)
}

fn copy_file_preserve_mode(src: &Path, dst: &Path) -> Result<(), String> {
    if let Some(parent) = dst.parent() {
        fs::create_dir_all(parent).map_err(|e| e.to_string())?;
    }
    let meta = fs::symlink_metadata(src).map_err(|e| format!("{}: {e}", src.display()))?;
    if meta.file_type().is_symlink() {
        let target = fs::read_link(src).map_err(|e| e.to_string())?;
        let _ = fs::remove_file(dst);
        std::os::unix::fs::symlink(&target, dst).map_err(|e| e.to_string())?;
        return Ok(());
    }
    fs::copy(src, dst).map_err(|e| format!("copy {} -> {}: {e}", src.display(), dst.display()))?;
    let _ = fs::set_permissions(dst, meta.permissions());
    Ok(())
}

fn copy_dir_recursive(src: &Path, dst: &Path) -> Result<(), String> {
    fs::create_dir_all(dst).map_err(|e| format!("mkdir {}: {e}", dst.display()))?;
    for ent in fs::read_dir(src).map_err(|e| format!("readdir {}: {e}", src.display()))? {
        let ent = ent.map_err(|e| e.to_string())?;
        let p = ent.path();
        let target = dst.join(ent.file_name());
        let meta = fs::symlink_metadata(&p).map_err(|e| e.to_string())?;
        if meta.file_type().is_dir() {
            copy_dir_recursive(&p, &target)?;
        } else {
            copy_file_preserve_mode(&p, &target)?;
        }
    }
    Ok(())
}

