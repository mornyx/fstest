fn stage_node_for_target(
    cache_root: &Path,
    downloads: &Path,
    stage: &Path,
    target_os: &str,
    target_arch: &str,
) -> Result<Value, String> {
    let plat = match (target_os, target_arch) {
        ("macos", "aarch64") => "darwin-arm64",
        ("macos", "x86_64") => "darwin-x64",
        ("linux", "x86_64") => "linux-x64",
        ("linux", "aarch64") => "linux-arm64",
        _ => return Err(format!("unsupported Node target {target_os}-{target_arch}")),
    };
    let bin_fname = format!("node-{NODE_VERSION}-{plat}.tar.gz");
    let bin_url = format!("https://nodejs.org/dist/{NODE_VERSION}/{bin_fname}");
    let bin_archive = download_cached(downloads, &bin_fname, &bin_url)?;

    let dst_node = stage.join("node");
    fs::create_dir_all(dst_node.join("bin")).map_err(|e| e.to_string())?;
    let want_entry = format!("node-{NODE_VERSION}-{plat}/bin/node");
    let node_out = dst_node.join("bin/node");
    {
        let f = File::open(&bin_archive).map_err(|e| e.to_string())?;
        let mut ar = tar::Archive::new(GzDecoder::new(f));
        let mut found = false;
        for entry in ar.entries().map_err(|e| e.to_string())? {
            let mut entry = entry.map_err(|e| e.to_string())?;
            if entry.path().map(|p| p == Path::new(&want_entry)).unwrap_or(false) {
                entry.unpack(&node_out).map_err(|e| e.to_string())?;
                found = true;
                break;
            }
        }
        if !found {
            return Err(format!("{} missing {want_entry}", bin_archive.display()));
        }
    }
    let _ = fs::set_permissions(&node_out, fs::Permissions::from_mode(0o755));
    if target_os == "linux" {
        maybe_strip_linux_elf(&node_out, target_arch);
    } else if target_os == "macos" {
        // Strip local symbols (~21 MiB saved) and refresh ad-hoc signature on Apple Silicon.
        let (host_os, _) = host_os_arch();
        if host_os == "macos" {
            let _ = Command::new("strip")
                .args(["-x"])
                .arg(&node_out)
                .stderr(std::process::Stdio::null())
                .status();
            let _ = Command::new("codesign")
                .args(["-s", "-", "-f"])
                .arg(&node_out)
                .stderr(std::process::Stdio::null())
                .status();
        }
    }
    verify_binary_arch(&node_out, target_os, target_arch)?;

    let node_tests_src = ensure_node_tests_cached(cache_root, downloads)?;
    copy_dir_recursive(&node_tests_src, &dst_node.join("test"))?;
    let fs_count = fs::read_dir(dst_node.join("test/parallel"))
        .map(|rd| rd.flatten().count())
        .unwrap_or(0);

    Ok(json!({
        "nodeVersion": NODE_VERSION,
        "platform": plat,
        "bundledRuntime": true,
        "files": fs_count,
    }))
}

fn ensure_node_tests_cached(cache_root: &Path, downloads: &Path) -> Result<PathBuf, String> {
    let cached = cache_root.join("sources").join(format!("node-{NODE_VERSION}-test-v3"));
    if cached.join("parallel").is_dir() && cached.join("common").is_dir() {
        return Ok(cached);
    }
    let fname = format!("node-{NODE_VERSION}-src.tar.gz");
    let url = format!("https://github.com/nodejs/node/archive/refs/tags/{NODE_VERSION}.tar.gz");
    let archive = download_cached(downloads, &fname, &url)?;

    let tmp_dir = cache_root
        .join("sources")
        .join(format!(".node-{NODE_VERSION}-test-v3.tmp-{}", std::process::id()));
    let _ = fs::remove_dir_all(&tmp_dir);
    fs::create_dir_all(tmp_dir.join("parallel")).map_err(|e| e.to_string())?;

    let root_prefix = format!("node-{}/test/", NODE_VERSION.trim_start_matches('v'));
    let f = File::open(&archive).map_err(|e| e.to_string())?;
    let mut ar = tar::Archive::new(GzDecoder::new(f));
    for entry in ar.entries().map_err(|e| e.to_string())? {
        let mut entry = entry.map_err(|e| e.to_string())?;
        let size = entry.size();
        let path_str = entry.path().map_err(|e| e.to_string())?.to_string_lossy().into_owned();
        let Some(rel) = path_str.strip_prefix(&root_prefix) else {
            continue;
        };
        let keep = if rel.starts_with("common/") {
            true
        } else if let Some(fix_rel) = rel.strip_prefix("fixtures/") {
            // Stage only the small fixtures actually referenced by `test-fs-*.js` (~1 MiB vs 37 MiB WPT/V8 bloat)
            (!fix_rel.contains('/') && size <= 65_536)
                || fix_rel.starts_with("cycles/")
                || fix_rel.starts_with("keys/")
                || fix_rel.starts_with("nested-index/")
        } else if let Some(fname) = rel.strip_prefix("parallel/") {
            fname.starts_with("test-fs-") && fname.ends_with(".js") && !NODE_STDFS_EXCLUDE.contains(&fname)
        } else {
            false
        };
        if keep {
            let dst = tmp_dir.join(rel);
            if let Some(parent) = dst.parent() {
                fs::create_dir_all(parent).map_err(|e| e.to_string())?;
            }
            let _ = entry.unpack(&dst);
        }
    }
    let _ = fs::remove_dir_all(&cached);
    fs::rename(&tmp_dir, &cached).map_err(|e| e.to_string())?;
    Ok(cached)
}

