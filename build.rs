fn empty_bundle_code() -> String {
    concat!(
        "// generated by build.rs (bundle embedding skipped)\n",
        "pub const EMBEDDED_BUNDLE_HASH: &str = \"\";\n",
        "pub static EMBEDDED_BUNDLE_BYTES: &[u8] = &[];\n",
    )
    .to_string()
}

fn cache_root_dir() -> PathBuf {
    if let Ok(d) = env::var("FSTEST_CACHE_DIR")
        && !d.trim().is_empty()
    {
        return PathBuf::from(d);
    }
    if let Ok(xdg) = env::var("XDG_CACHE_HOME")
        && !xdg.trim().is_empty()
    {
        return PathBuf::from(xdg).join("fstest");
    }
    if let Ok(home) = env::var("HOME")
        && !home.trim().is_empty()
    {
        return PathBuf::from(home).join(".cache/fstest");
    }
    env::temp_dir().join("fstest-build-cache")
}

fn host_os_arch() -> (String, String) {
    let host = env::var("HOST").unwrap_or_default();
    let arch = if host.starts_with("aarch64-") {
        "aarch64"
    } else if host.starts_with("x86_64-") {
        "x86_64"
    } else {
        env::consts::ARCH
    };
    let os = if host.contains("apple-darwin") {
        "macos"
    } else if host.contains("linux") {
        "linux"
    } else {
        env::consts::OS
    };
    (os.to_string(), arch.to_string())
}

fn generate_embedded_suite_bundle() -> String {
    if env::var("CARGO_FEATURE_EMBED_BUNDLE").is_err() || env::var("FSTEST_SKIP_BUNDLE").as_deref() == Ok("1") {
        return empty_bundle_code();
    }

    let target_os = env::var("CARGO_CFG_TARGET_OS").unwrap_or_default();
    let target_arch = env::var("CARGO_CFG_TARGET_ARCH").unwrap_or_default();
    let supported = matches!(
        (target_os.as_str(), target_arch.as_str()),
        ("macos", "aarch64") | ("macos", "x86_64") | ("linux", "x86_64") | ("linux", "aarch64")
    );
    if !supported {
        return empty_bundle_code();
    }

    let cache_root = cache_root_dir();
    let target_key = format!("{target_os}-{target_arch}-{BUNDLE_RECIPE_VERSION}");
    let bundle_dir = cache_root.join("target-bundles").join(&target_key);
    let tar_gz_path = bundle_dir.join("bundle.tar.gz");
    let hash_path = bundle_dir.join("bundle.sha256");

    let force_rebuild = env::var("FSTEST_REBUILD_BUNDLE").as_deref() == Ok("1");
    if !force_rebuild
        && tar_gz_path.is_file()
        && let Ok(h) = fs::read_to_string(&hash_path)
    {
        let hash = h.trim();
        if !hash.is_empty() {
            return format!(
                "// generated by build.rs; DO NOT EDIT\npub const EMBEDDED_BUNDLE_HASH: &str = {:?};\npub static EMBEDDED_BUNDLE_BYTES: &[u8] = include_bytes!({:?});\n",
                hash, tar_gz_path
            );
        }
    }

    println!(
        "cargo:warning=fstest: preparing self-contained suite bundle for {target_os}-{target_arch} (first-time build, cached under {})...",
        bundle_dir.display()
    );

    let hash = build_target_bundle(&cache_root, &bundle_dir, &target_os, &target_arch)
        .unwrap_or_else(|e| {
            panic!(
                "fstest build.rs failed to prepare embedded suite bundle for {target_os}-{target_arch}: {e}\n(set FSTEST_SKIP_BUNDLE=1 or --no-default-features to build without embedded external suites)"
            )
        });

    format!(
        "// generated by build.rs; DO NOT EDIT\npub const EMBEDDED_BUNDLE_HASH: &str = {:?};\npub static EMBEDDED_BUNDLE_BYTES: &[u8] = include_bytes!({:?});\n",
        hash, tar_gz_path
    )
}

fn build_target_bundle(
    cache_root: &Path,
    bundle_dir: &Path,
    target_os: &str,
    target_arch: &str,
) -> Result<String, String> {
    let downloads = cache_root.join("downloads");
    fs::create_dir_all(&downloads).map_err(|e| e.to_string())?;
    fs::create_dir_all(bundle_dir).map_err(|e| e.to_string())?;

    let stage = bundle_dir.join(format!("stage.tmp-{}", std::process::id()));
    let _ = fs::remove_dir_all(&stage);
    fs::create_dir_all(&stage).map_err(|e| e.to_string())?;

    let mut components = Map::new();

    // 1. Go precompiled stdlib test binaries (`os`, `path/filepath`, `io/fs`)
    let go_meta = stage_go_for_target(cache_root, &downloads, &stage, target_os, target_arch)?;
    components.insert("go".into(), go_meta);

    // 2. Relocatable Python runtime + matching CPython `Lib/test` FS suite
    let py_meta = stage_python_for_target(cache_root, &downloads, &stage, target_os, target_arch)?;
    components.insert("python".into(), py_meta);

    // 3. Node.js runtime + matching `test/parallel/test-fs-*.js` suite
    let node_meta = stage_node_for_target(cache_root, &downloads, &stage, target_os, target_arch)?;
    components.insert("node".into(), node_meta);

    // 4, 5 & 6. Git (`t/` suite + same-source binaries), Fio (`axboe/fio`), & LTP (Linux targets only)
    let (git_tree, ltp_prefix, fio_bin) = ensure_git_ltp_and_fio_built(cache_root, &downloads, target_os, target_arch)?;
    let git_meta = stage_git_from_tree(&git_tree, &stage, target_os, target_arch)?;
    components.insert("git".into(), git_meta);

    let fio_meta = stage_fio_from_bin(&fio_bin, &stage, target_os, target_arch)?;
    components.insert("fio".into(), fio_meta);

    if let Some(ltp_dir) = ltp_prefix {
        let ltp_meta = stage_ltp_from_prefix(&ltp_dir, &stage, target_os, target_arch)?;
        components.insert("ltp".into(), ltp_meta);
    }

    let manifest = json!({
        "version": 2,
        "recipe": BUNDLE_RECIPE_VERSION,
        "os": target_os,
        "arch": target_arch,
        "components": components,
    });
    let manifest_bytes = serde_json::to_vec_pretty(&manifest).unwrap();
    fs::write(stage.join("manifest.json"), &manifest_bytes).map_err(|e| e.to_string())?;

    let tmp_tar = bundle_dir.join(format!("bundle.tar.gz.tmp-{}", std::process::id()));
    let _ = fs::remove_file(&tmp_tar);
    {
        let out_f = File::create(&tmp_tar).map_err(|e| e.to_string())?;
        let enc = GzEncoder::new(out_f, Compression::default());
        let mut tar = tar::Builder::new(enc);
        tar.follow_symlinks(false);
        // Put `manifest.json` first so `fstest bundle info` reads only the first KB of the stream.
        tar.append_path_with_name(stage.join("manifest.json"), "manifest.json")
            .map_err(|e| format!("archiving manifest.json: {e}"))?;
        let mut top_entries: Vec<_> = fs::read_dir(&stage).map_err(|e| e.to_string())?.flatten().collect();
        top_entries.sort_by_key(|e| e.file_name());
        for ent in top_entries {
            let name = ent.file_name();
            if name == "manifest.json" {
                continue;
            }
            let p = ent.path();
            let rel = Path::new(&name);
            if p.is_dir() {
                tar.append_dir_all(rel, &p)
                    .map_err(|e| format!("archiving {}: {e}", p.display()))?;
            } else {
                tar.append_path_with_name(&p, rel)
                    .map_err(|e| format!("archiving {}: {e}", p.display()))?;
            }
        }
        let enc = tar.into_inner().map_err(|e| e.to_string())?;
        enc.finish().map_err(|e| e.to_string())?;
    }
    let _ = fs::remove_dir_all(&stage);

    let hash = sha256_prefix16(&tmp_tar)?;
    let final_tar = bundle_dir.join("bundle.tar.gz");
    fs::rename(&tmp_tar, &final_tar).map_err(|e| e.to_string())?;
    fs::write(bundle_dir.join("bundle.sha256"), format!("{hash}\n")).map_err(|e| e.to_string())?;
    Ok(hash)
}

// ---------- Component 1: Go stdlib tests ----------

fn ensure_host_go(cache_root: &Path, downloads: &Path) -> Result<PathBuf, String> {
    if let Some(go) = find_in_path("go") {
        return Ok(go);
    }
    let (host_os, host_arch) = host_os_arch();
    let goos = match host_os.as_str() {
        "macos" => "darwin",
        "linux" => "linux",
        other => return Err(format!("go not found on PATH and unsupported host OS {other}")),
    };
    let goarch = match host_arch.as_str() {
        "aarch64" => "arm64",
        "x86_64" => "amd64",
        other => return Err(format!("go not found on PATH and unsupported host arch {other}")),
    };
    let go_root = cache_root
        .join("toolchains")
        .join(format!("go-{GO_FALLBACK_VERSION}-{goos}-{goarch}"))
        .join("go");
    let go_bin = go_root.join("bin/go");
    if go_bin.is_file() {
        return Ok(go_bin);
    }
    let fname = format!("go{GO_FALLBACK_VERSION}.{goos}-{goarch}.tar.gz");
    let url = format!("https://go.dev/dl/{fname}");
    let archive = download_cached(downloads, &fname, &url)?;
    let dest_parent = go_root.parent().unwrap();
    fs::create_dir_all(dest_parent).map_err(|e| e.to_string())?;
    unpack_tar_gz(&archive, dest_parent)?;
    if !go_bin.is_file() {
        return Err(format!("downloaded Go archive did not produce {}", go_bin.display()));
    }
    Ok(go_bin)
}

fn stage_go_for_target(
    cache_root: &Path,
    downloads: &Path,
    stage: &Path,
    target_os: &str,
    target_arch: &str,
) -> Result<Value, String> {
    let go = ensure_host_go(cache_root, downloads)?;
    let goroot = Command::new(&go)
        .args(["env", "GOROOT"])
        .output()
        .ok()
        .filter(|o| o.status.success())
        .map(|o| PathBuf::from(String::from_utf8_lossy(&o.stdout).trim()))
        .ok_or_else(|| format!("`{} env GOROOT` failed", go.display()))?;
    let goos = match target_os {
        "macos" => "darwin",
        "linux" => "linux",
        other => return Err(format!("unsupported Go target_os: {other}")),
    };
    let goarch = match target_arch {
        "aarch64" => "arm64",
        "x86_64" => "amd64",
        other => return Err(format!("unsupported Go target_arch: {other}")),
    };
    let out_dir = stage.join("go");
    fs::create_dir_all(&out_dir).map_err(|e| e.to_string())?;
    let pkgs = ["os", "path/filepath", "io/fs"];
    for pkg in pkgs {
        let safe = pkg.replace(['/', '.'], "_");
        let bin = out_dir.join(format!("go_{safe}.test"));
        let status = Command::new(&go)
            .env("CGO_ENABLED", "0")
            .env("GOOS", goos)
            .env("GOARCH", goarch)
            .args(["test", "-ldflags=-s -w", "-c", "-o"])
            .arg(&bin)
            .arg(pkg)
            .current_dir(&out_dir)
            .status()
            .map_err(|e| format!("spawn go test -c {pkg}: {e}"))?;
        if !status.success() {
            return Err(format!("go test -c {pkg} failed for {goos}/{goarch}"));
        }
        let _ = fs::set_permissions(&bin, fs::Permissions::from_mode(0o755));
        verify_binary_arch(&bin, target_os, target_arch)?;

        // Stage lightweight package source/testdata skeleton (~420 KiB total across all 3 packages)
        // so `TestReadDir`, `TestReadFile`, `TestReaddirSmallSeek`, `TestDirFS`, `TestCopyFS`, and
        // `TestGlob` all execute directly against the mounted filesystem with zero default skips.
        let pkg_src = goroot.join("src").join(pkg);
        let fix_dst = out_dir.join("fixtures").join(pkg);
        fs::create_dir_all(&fix_dst).map_err(|e| e.to_string())?;
        if let Ok(rd) = fs::read_dir(&pkg_src) {
            for ent in rd.flatten() {
                let p = ent.path();
                let fname = ent.file_name().to_string_lossy().into_owned();
                if p.is_file() && fname.ends_with(".go") {
                    fs::copy(&p, fix_dst.join(&fname)).map_err(|e| e.to_string())?;
                } else if p.is_dir() && fname == "testdata" {
                    copy_dir_recursive(&p, &fix_dst.join("testdata"))?;
                }
            }
        }
        if pkg == "os" {
            // `os.TestReadDir` asserts an `exec` directory entry exists in `.` (mirroring `src/os/exec`).
            fs::create_dir_all(fix_dst.join("exec")).map_err(|e| e.to_string())?;
            fs::write(fix_dst.join("exec/.keep"), b"").map_err(|e| e.to_string())?;
        }
    }
    Ok(json!({
        "goos": goos,
        "goarch": goarch,
        "packages": pkgs,
        "stagedFixtures": true,
    }))
}

// ---------- Component 2: Standalone Python + Lib/test ----------

fn stage_python_for_target(
    cache_root: &Path,
    downloads: &Path,
    stage: &Path,
    target_os: &str,
    target_arch: &str,
) -> Result<Value, String> {
    let triple = match (target_os, target_arch) {
        ("macos", "aarch64") => "aarch64-apple-darwin",
        ("macos", "x86_64") => "x86_64-apple-darwin",
        ("linux", "x86_64") => "x86_64-unknown-linux-gnu",
        ("linux", "aarch64") => "aarch64-unknown-linux-gnu",
        _ => return Err(format!("unsupported Python target {target_os}-{target_arch}")),
    };
    let rt_fname = format!("cpython-{PY_VERSION}+{PY_STANDALONE_TAG}-{triple}-install_only_stripped.tar.gz");
    let rt_url = format!(
        "https://github.com/astral-sh/python-build-standalone/releases/download/{PY_STANDALONE_TAG}/cpython-{PY_VERSION}%2B{PY_STANDALONE_TAG}-{triple}-install_only_stripped.tar.gz"
    );
    let rt_archive = download_cached(downloads, &rt_fname, &rt_url)?;

    // Unpack `python/` directly under `stage/` -> `stage/python/bin/python3`, `stage/python/lib/python3.12`
    unpack_tar_gz(&rt_archive, stage)?;
    let py_root = stage.join("python");
    let py_bin = py_root.join("bin/python3.12");
    verify_binary_arch(&py_bin, target_os, target_arch)?;

    // Prune non-FS bloat: `python-build-standalone` statically links CPython into `bin/python3.12`,
    // so the duplicate `libpython3.12.{dylib,so*}` (17-32 MiB) and Tcl/Tk GUI libraries (~8 MiB)
    // are completely unused at runtime.
    let stdlib = py_root.join("lib/python3.12");
    for bloat in [
        "include",
        "share",
        "lib/pkgconfig",
        "lib/python3.12/site-packages",
        "lib/python3.12/ensurepip",
        "lib/python3.12/idlelib",
        "lib/python3.12/tkinter",
        "lib/python3.12/turtledemo",
        "lib/python3.12/pydoc_data",
        "lib/python3.12/lib2to3",
        "lib/python3.12/_pydecimal.py",
        "lib/python3.12/turtle.py",
    ] {
        let p = py_root.join(bloat);
        let _ = if p.is_dir() {
            fs::remove_dir_all(&p)
        } else {
            fs::remove_file(&p)
        };
    }
    if let Ok(rd) = fs::read_dir(py_root.join("lib")) {
        for ent in rd.flatten() {
            let fname = ent.file_name().to_string_lossy().into_owned();
            let drop_lib = fname.starts_with("libpython")
                || fname.starts_with("libtcl")
                || fname.starts_with("tcl")
                || fname.starts_with("tk")
                || fname.starts_with("itcl")
                || fname.starts_with("thread");
            if drop_lib {
                let p = ent.path();
                let _ = if p.is_dir() {
                    fs::remove_dir_all(&p)
                } else {
                    fs::remove_file(&p)
                };
            }
        }
    }
    if let Ok(rd) = fs::read_dir(stdlib.join("lib-dynload")) {
        for ent in rd.flatten() {
            let fname = ent.file_name().to_string_lossy().into_owned();
            if fname.starts_with("_tkinter") {
                let _ = fs::remove_file(ent.path());
            }
        }
    }

    // Populate matching CPython v3.12.16 `Lib/test` subset into `stage/python/lib/python3.12/test`
    let cpy_src_test = ensure_cpython_lib_test_cached(cache_root, downloads)?;
    let dst_test = stdlib.join("test");
    let _ = fs::remove_dir_all(&dst_test);
    fs::create_dir_all(&dst_test).map_err(|e| e.to_string())?;

    for d in ["support", "libregrtest", "os_helper"] {
        if cpy_src_test.join(d).is_dir() {
            copy_dir_recursive(&cpy_src_test.join(d), &dst_test.join(d))?;
        }
    }
    let mut copied_files = 0usize;
    for ent in fs::read_dir(&cpy_src_test).map_err(|e| e.to_string())?.flatten() {
        let p = ent.path();
        let name = ent.file_name().to_string_lossy().into_owned();
        if p.is_file() {
            let size = ent.metadata().map(|m| m.len()).unwrap_or(u64::MAX);
            let keep = if name.starts_with("test_") {
                matches!(
                    name.as_str(),
                    "test_os.py"
                        | "test_posix.py"
                        | "test_posixpath.py"
                        | "test_genericpath.py"
                        | "test_pathlib.py"
                        | "test_shutil.py"
                        | "test_tarfile.py"
                        | "test_stat.py"
                        | "test_fileio.py"
                        | "test_glob.py"
                        | "test_tempfile.py"
                        | "test_mmap.py"
                        | "test_fcntl.py"
                        | "test_support.py"
                )
            } else {
                // Include helper `.py` files and archive fixtures such as `testtar.tar` (~425 KiB)
                name.ends_with(".py") || size <= 524_288
            };
            if keep {
                fs::copy(&p, dst_test.join(&name)).map_err(|e| e.to_string())?;
                copied_files += 1;
            }
        } else if p.is_dir()
            && matches!(
                name.as_str(),
                "test_os" | "test_importlib" | "archivetestdata" | "ziptestdata" | "tokenizedata"
            )
        {
            copy_dir_recursive(&p, &dst_test.join(&name))?;
        }
    }

    // Also expose `stage/python/Lib` symlink -> `lib/python3.12` so any external interpreter fallback works too
    let _ = std::os::unix::fs::symlink("lib/python3.12", py_root.join("Lib"));

    Ok(json!({
        "pythonVersion": PY_VERSION,
        "triple": triple,
        "bundledRuntime": true,
        "testFiles": copied_files,
    }))
}

fn ensure_cpython_lib_test_cached(cache_root: &Path, downloads: &Path) -> Result<PathBuf, String> {
    let extracted_marker = cache_root
        .join("sources")
        .join(format!("cpython-{PY_VERSION}-lib-test"));
    if extracted_marker.join("libregrtest").is_dir() && extracted_marker.join("test_os.py").is_file() {
        return Ok(extracted_marker);
    }
    let fname = format!("cpython-v{PY_VERSION}-src.tar.gz");
    let url = format!("https://github.com/python/cpython/archive/refs/tags/v{PY_VERSION}.tar.gz");
    let archive = download_cached(downloads, &fname, &url)?;

    let tmp_dir = cache_root
        .join("sources")
        .join(format!(".cpython-{PY_VERSION}.tmp-{}", std::process::id()));
    let _ = fs::remove_dir_all(&tmp_dir);
    fs::create_dir_all(&tmp_dir).map_err(|e| e.to_string())?;

    let prefix = format!("cpython-{PY_VERSION}/Lib/test/");
    let f = File::open(&archive).map_err(|e| e.to_string())?;
    let mut ar = tar::Archive::new(GzDecoder::new(f));
    for entry in ar.entries().map_err(|e| e.to_string())? {
        let mut entry = entry.map_err(|e| e.to_string())?;
        let path_str = entry.path().map_err(|e| e.to_string())?.to_string_lossy().into_owned();
        if let Some(rel) = path_str.strip_prefix(&prefix)
            && !rel.is_empty()
        {
            let dst = tmp_dir.join(rel);
            if let Some(parent) = dst.parent() {
                fs::create_dir_all(parent).map_err(|e| e.to_string())?;
            }
            entry.unpack(&dst).map_err(|e| e.to_string())?;
        }
    }
    let _ = fs::remove_dir_all(&extracted_marker);
    fs::rename(&tmp_dir, &extracted_marker).map_err(|e| e.to_string())?;
    Ok(extracted_marker)
}

