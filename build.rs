fn valid_git_tree(dir: &Path, target_os: &str, target_arch: &str) -> bool {
    dir.join("t/test-lib.sh").is_file()
        && matches_target_binary(&dir.join("git"), target_os, target_arch)
        && matches_target_binary(&dir.join("t/helper/test-tool"), target_os, target_arch)
}

fn valid_ltp_prefix(dir: &Path, target_os: &str, target_arch: &str) -> bool {
    if !dir.join("runtest/syscalls").is_file()
        || !dir.join("runtest/fs").is_file()
        || !dir.join("testcases/bin").is_dir()
    {
        return false;
    }
    // Verify representative binaries across `syscalls` (`open01`), child helpers (`creat07_child`),
    // `fs` (`ftest01` + `writetest`), and `fcntl-locktests` (`locktests`) match the target ELF arch.
    for probe in ["open01", "creat07_child", "ftest01", "writetest", "locktests"] {
        let p = dir.join("testcases/bin").join(probe);
        if !matches_target_binary(&p, target_os, target_arch) {
            return false;
        }
    }
    true
}

const LIBAIO_STATIC_SHIM_C: &str = r#"#define _GNU_SOURCE
#include <errno.h>
#include <libaio.h>
#include <string.h>
#include <sys/syscall.h>
#include <unistd.h>

int io_setup(int maxevents, io_context_t *ctxp) {
    long r = syscall(__NR_io_setup, (unsigned)maxevents, ctxp);
    return r < 0 ? -errno : 0;
}
int io_destroy(io_context_t ctx) {
    long r = syscall(__NR_io_destroy, ctx);
    return r < 0 ? -errno : 0;
}
int io_queue_init(int maxevents, io_context_t *ctxp) {
    if (!ctxp) return -EINVAL;
    memset(ctxp, 0, sizeof(*ctxp));
    return io_setup(maxevents, ctxp);
}
int io_queue_release(io_context_t ctx) {
    return io_destroy(ctx);
}
int io_submit(io_context_t ctx, long nr, struct iocb *ios[]) {
    long r = syscall(__NR_io_submit, ctx, nr, ios);
    return r < 0 ? -errno : (int)r;
}
int io_getevents(io_context_t ctx, long min_nr, long nr, struct io_event *events, struct timespec *timeout) {
    long r = syscall(__NR_io_getevents, ctx, min_nr, nr, events, timeout);
    return r < 0 ? -errno : (int)r;
}
int io_cancel(io_context_t ctx, struct iocb *iocb, struct io_event *evt) {
    long r = syscall(__NR_io_cancel, ctx, iocb, evt);
    return r < 0 ? -errno : (int)r;
}
"#;

