fn collect(dir: &Path, prefix: &str, out: &mut Vec<(String, PathBuf)>) {
    for entry in fs::read_dir(dir).expect("cannot read vendored tests dir") {
        let entry = entry.unwrap();
        let path = entry.path();
        let name = entry.file_name().into_string().unwrap();
        if name.starts_with("._") || name == ".DS_Store" {
            continue;
        }
        let rel = if prefix.is_empty() {
            name.clone()
        } else {
            format!("{prefix}/{name}")
        };
        if path.is_dir() {
            collect(&path, &rel, out);
        } else {
            out.push((rel, path));
        }
    }
}

fn locate_rust_fs_tests_rs() -> Option<PathBuf> {
    if let Ok(d) = env::var("FSTEST_BUILD_RUST_SRC")
        && !d.trim().is_empty()
    {
        let p = PathBuf::from(d).join("std/src/fs/tests.rs");
        if p.is_file() {
            return Some(p);
        }
    }
    let rustc = env::var("RUSTC").unwrap_or_else(|_| "rustc".to_string());
    let out = Command::new(&rustc).args(["--print", "sysroot"]).output().ok()?;
    if !out.status.success() {
        return None;
    }
    let sysroot = String::from_utf8_lossy(&out.stdout).trim().to_string();
    let p = PathBuf::from(&sysroot).join("lib/rustlib/src/rust/library/std/src/fs/tests.rs");
    if p.is_file() {
        return Some(p);
    }
    // When building a self-contained binary (`embed-bundle`), attempt `rustup component add rust-src`
    // automatically so `fstest stdfs --lang rust` never degrades silently on target hosts.
    if env::var("CARGO_FEATURE_EMBED_BUNDLE").is_ok()
        && env::var("FSTEST_SKIP_BUNDLE").as_deref() != Ok("1")
        && find_in_path("rustup").is_some()
    {
        let _ = Command::new("rustup").args(["component", "add", "rust-src"]).status();
        if p.is_file() {
            return Some(p);
        }
    }
    if env::var("CARGO_FEATURE_EMBED_BUNDLE").is_ok() {
        println!(
            "cargo:warning=fstest: rust-src not found at {}; `fstest stdfs --lang rust` will require --rust-src-dir at runtime (install `rustup component add rust-src`)",
            p.display()
        );
    }
    None
}

fn read_attr(lines: &[&str], mut j: usize) -> (String, usize) {
    let mut text = String::new();
    let mut depth: i32 = 0;
    while j < lines.len() {
        for ch in lines[j].chars() {
            match ch {
                '[' => depth += 1,
                ']' => depth -= 1,
                _ => {}
            }
        }
        if !text.is_empty() {
            text.push(' ');
        }
        text.push_str(lines[j].trim());
        j += 1;
        if depth <= 0 {
            break;
        }
    }
    (text, j)
}

fn generate_embedded_rust_stdfs() -> String {
    let Some(tests_rs) = locate_rust_fs_tests_rs() else {
        return concat!(
            "// generated by build.rs (rust-src not present at build time)\n",
            "pub const EMBEDDED_AVAILABLE: bool = false;\n",
            "pub const EMBEDDED_SOURCE: &str = \"\";\n",
            "pub static EMBEDDED_EXCLUDED: &[(&str, &str)] = &[];\n",
            "pub static EMBEDDED_TESTS: &[(&str, fn(), bool)] = &[];\n",
        )
        .to_string();
    };
    let Ok(src) = fs::read_to_string(&tests_rs) else {
        return concat!(
            "pub const EMBEDDED_AVAILABLE: bool = false;\n",
            "pub const EMBEDDED_SOURCE: &str = \"\";\n",
            "pub static EMBEDDED_EXCLUDED: &[(&str, &str)] = &[];\n",
            "pub static EMBEDDED_TESTS: &[(&str, fn(), bool)] = &[];\n",
        )
        .to_string();
    };

    let lines: Vec<&str> = src.lines().collect();
    let mut skip: Vec<(usize, usize)> = Vec::new();
    let mut drops: Vec<usize> = Vec::new();
    let mut attr_drops: Vec<(usize, usize)> = Vec::new();
    let mut pubs: Vec<usize> = Vec::new();
    let mut tests: Vec<(Vec<String>, String, bool)> = Vec::new();
    let mut excluded: Vec<(String, &'static str)> = Vec::new();
    let mut i = 0;
    while i < lines.len() {
        if lines[i].trim() != "#[test]" {
            i += 1;
            continue;
        }
        let mut back = i;
        while back > 0 {
            let t = lines[back - 1].trim();
            if t.is_empty() || t.starts_with("#[") || t.starts_with("//") {
                back -= 1;
            } else {
                break;
            }
        }
        let mut collected_attrs: Vec<String> = Vec::new();
        let mut b = back;
        while b < i {
            let t = lines[b].trim();
            if t.starts_with("#[") {
                let (text, nb) = read_attr(&lines, b);
                if text.contains("should_panic") || text.starts_with("#[ignore") {
                    attr_drops.push((b, nb - 1));
                }
                collected_attrs.push(text);
                b = nb;
            } else {
                b += 1;
            }
        }
        let mut j = i + 1;
        let mut name = String::new();
        while j < lines.len() {
            let t = lines[j].trim();
            if t.starts_with("#[") {
                let (text, nj) = read_attr(&lines, j);
                if text.contains("should_panic") || text.starts_with("#[ignore") {
                    attr_drops.push((j, nj - 1));
                }
                collected_attrs.push(text);
                j = nj;
                continue;
            }
            if t.starts_with("//") || t.starts_with("/*") || t.is_empty() {
                j += 1;
                continue;
            }
            if t.starts_with("fn ") || t.starts_with("pub fn ") || t.starts_with("async fn ") {
                name = t
                    .split("fn ")
                    .nth(1)
                    .unwrap_or("")
                    .split(['(', '<', ':'])
                    .next()
                    .unwrap_or("")
                    .trim()
                    .to_string();
                break;
            }
            break;
        }
        if name.is_empty() {
            i += 1;
            continue;
        }
        let mut depth: i32 = 0;
        let mut seen = false;
        let mut end = j;
        while end < lines.len() {
            for ch in lines[end].chars() {
                match ch {
                    '{' => {
                        depth += 1;
                        seen = true;
                    }
                    '}' => depth -= 1,
                    _ => {}
                }
            }
            if seen && depth <= 0 {
                break;
            }
            end += 1;
        }
        let uses_internal_dir = lines[j..=end.min(lines.len().saturating_sub(1))]
            .iter()
            .any(|l| l.contains("Dir::") || l.contains("set_permissions_nofollow"));
        if let Some(&(_, reason)) = RUST_STD_EXCLUDE.iter().find(|&&(n, _)| n == name) {
            skip.push((back, end));
            excluded.push((name, reason));
        } else if uses_internal_dir {
            skip.push((back, end));
            excluded.push((name, "uses unstable std-internal fs::Dir"));
        } else {
            drops.push(i);
            pubs.push(j);
            let ignored = collected_attrs.iter().any(|a| a.starts_with("#[ignore"));
            let cfg_attrs: Vec<String> = collected_attrs
                .into_iter()
                .filter(|a| a.starts_with("#[cfg(") || a.starts_with("#[cfg_attr("))
                .collect();
            tests.push((cfg_attrs, name, ignored));
        }
        i = end + 1;
    }

    let in_ranges = |ln: usize, rs: &[(usize, usize)]| rs.iter().any(|&(s, e)| ln >= s && ln <= e);
    let mut transformed = String::with_capacity(src.len() + 8192);
    for (ln, &raw) in lines.iter().enumerate() {
        if in_ranges(ln, &skip) || in_ranges(ln, &attr_drops) || drops.contains(&ln) {
            continue;
        }
        if raw.trim() == "use super::Dir;" {
            continue;
        }
        let mut s = raw.to_string();
        if pubs.contains(&ln)
            && s.trim_start().starts_with("fn ")
            && let Some(pos) = s.find("fn ")
        {
            s.insert_str(pos, "pub ");
        }
        s = s.replace("crate::", "std::");
        s = s.replace("std::test_helpers", "super::shim::test_helpers");
        s = s.replace("use std::io::{BorrowedBuf, ", "use std::io::{");
        if s.trim() == "use rand::RngCore;" {
            s = "use super::shim::rand::RngCore;".to_string();
        }
        if s.trim() == "use std::{assert_matches, env, io, str, thread};" {
            s = "use super::shim::assert_matches;\nuse std::{env, io, str, thread};".to_string();
        }
        transformed.push_str(&s);
        transformed.push('\n');
    }

    let mut code = String::with_capacity(transformed.len() + 16384);
    code.push_str("// generated by build.rs; DO NOT EDIT\n");
    code.push_str("pub const EMBEDDED_AVAILABLE: bool = true;\n");
    code.push_str(&format!(
        "pub const EMBEDDED_SOURCE: &str = {:?};\n",
        tests_rs.display().to_string()
    ));
    code.push_str("pub static EMBEDDED_EXCLUDED: &[(&str, &str)] = &[\n");
    for (n, r) in &excluded {
        code.push_str(&format!("    ({:?}, {:?}),\n", n, r));
    }
    code.push_str("];\n\n");
    code.push_str("#[allow(warnings, unsafe_op_in_unsafe_fn, dead_code, unused_imports, non_snake_case)]\n");
    code.push_str("mod tests_impl {\n");
    code.push_str(&transformed);
    code.push_str("}\n");
    code.push_str("pub static EMBEDDED_TESTS: &[(&str, fn(), bool)] = &[\n");
    for (cfgs, n, ignored) in &tests {
        for c in cfgs {
            code.push_str("    ");
            code.push_str(c);
            code.push('\n');
        }
        code.push_str(&format!("    ({:?}, tests_impl::{}, {}),\n", n, n, ignored));
    }
    code.push_str("];\n");
    code
}
