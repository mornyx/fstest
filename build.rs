fn main() {
    let root = PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap());
    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap());

    // 1. Embed vendored pjdfstest shell suite
    let tests_dir = root.join("vendor/pjdfstest/tests");
    println!("cargo:rerun-if-changed=vendor/pjdfstest/tests");
    println!("cargo:rerun-if-changed=vendor/ltp");
    let mut files: Vec<(String, PathBuf)> = Vec::new();
    collect(&tests_dir, "", &mut files);
    files.sort();
    let mut out =
        String::from("// generated by build.rs; DO NOT EDIT\n\npub static TEST_FILES: &[(&str, &str)] = &[\n");
    for (rel, abs) in &files {
        let content = fs::read(abs).unwrap_or_else(|e| panic!("cannot read {}: {e}", abs.display()));
        std::str::from_utf8(&content).unwrap_or_else(|e| panic!("{} is not valid UTF-8: {e}", abs.display()));
        out.push_str(&format!("    ({:?}, include_str!({:?})),\n", rel, abs));
    }
    out.push_str("];\n");
    fs::write(out_dir.join("pjdfstest_files.rs"), out).unwrap();

    // 2. Embed Rust std::fs test suite from the build toolchain's rust-src (when available),
    // so `fstest stdfs --lang rust` runs with zero target-host rustc / rust-src dependency.
    println!("cargo:rerun-if-env-changed=FSTEST_BUILD_RUST_SRC");
    let embedded_rs = generate_embedded_rust_stdfs();
    fs::write(out_dir.join("stdfs_rust_embedded.rs"), embedded_rs).unwrap();

    // 3. Build & embed target-platform suite bundle (`stdfs` Go/Python/Node, `git`, and
    //    `ltp` on Linux) so `cargo build` directly produces a single self-contained binary.
    println!("cargo:rerun-if-env-changed=FSTEST_SKIP_BUNDLE");
    println!("cargo:rerun-if-env-changed=FSTEST_REBUILD_BUNDLE");
    println!("cargo:rerun-if-env-changed=FSTEST_CACHE_DIR");
    let bundle_rs = generate_embedded_suite_bundle();
    fs::write(out_dir.join("embedded_bundle.rs"), bundle_rs).unwrap();
}

